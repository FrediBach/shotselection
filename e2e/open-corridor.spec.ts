import { expect, test } from '@playwright/test'
import { DEFAULT_CHARACTER } from '../src/engine/characters'
import { generateScenario } from '../src/engine/scenarios'
import { prepareRound } from '../src/engine/preparation'
import { startLevel } from './helpers'

for (const mobile of [true, false]) test(`open a corridor on ${mobile ? 'mobile' : 'desktop'}`, async ({ page }) => {
  await page.setViewportSize(mobile ? { width: 390, height: 844 } : { width: 1440, height: 1050 })
  await page.addInitScript(character => {
    localStorage.setItem('shot-selection-help-dismissed', 'true')
    localStorage.setItem('shot-selection-sound-enabled', 'false')
    localStorage.setItem('shot-selection-session', JSON.stringify({ character, scoringVersion: 2, courseVersion: 5, completedLessons: 44, level: 45, score: 0, rounds: 44, perfect: 0, seed: 0 }))
    const original = HTMLCanvasElement.prototype.getContext
    HTMLCanvasElement.prototype.getContext = function(type: string, ...args: unknown[]) { if (type === 'webgl2') return null; return original.call(this, type as '2d', ...args) } as typeof original
  }, DEFAULT_CHARACTER)
  const p = prepareRound(generateScenario(45, 45 * 919), { regenerate: false }), c = p.openCorridor!
  const options = p.balls.flatMap(b => b.options)
  const selected = mobile ? options.find(o => o.id === c.blockedId)! : p.balls[0].options.find(o => o.id !== c.openedId)!
  await page.goto('/'); await startLevel(page, 45)
  const panel = page.getByRole('region', { name: 'Opening a corridor comparison', exact: true })
  const predictions = panel.getByRole('group', { name: 'Corridor-opening prediction', exact: true })
  await expect(panel).toBeVisible()
  await expect(panel.getByRole('img')).toHaveCount(0)
  await expect(page.getByRole('button', { name: 'Select ball 2', exact: true })).toBeDisabled()
  if (mobile) await predictions.getByRole('button', { name: 'Pot ball 3', exact: true }).click()
  await page.getByRole('button', { name: `Select ball ${selected.plan.ballId}`, exact: true }).click()
  await page.getByRole('button', { name: 'Choose a finish', exact: true }).click()
  await page.getByRole('button', { name: `Choose finish ${selected.label}`, exact: true }).click()
  await page.getByRole('button', { name: 'Lock in your shot', exact: true }).click()
  await expect(panel.getByRole('status')).toContainText(mobile ? 'Potting ball 3 leaves the blocker' : 'Compare what remains after each pot', { timeout: 30000 })
  await expect(panel).toContainText(mobile ? 'one of these reference shots' : 'another option')
  for (const button of await predictions.getByRole('button').all()) await expect(button).toBeDisabled()
  await expect(panel.getByRole('img')).toHaveCount(2)
  const blocked = panel.getByRole('img', { name: 'After potting ball 3: ball 1 still blocks the pocket line', exact: true })
  const opened = panel.getByRole('img', { name: 'After potting ball 1: the next corridor is open', exact: true })
  expect(await blocked.locator('text').allTextContents()).toContain('1')
  expect(await blocked.locator('text').allTextContents()).not.toContain('3')
  expect(await opened.locator('text').allTextContents()).not.toContain('1')
  expect(await opened.locator('text').allTextContents()).toContain('3')
  await expect(page.locator('.perfect-celebration')).toHaveCount(0, { timeout: 10000 })
  await opened.scrollIntoViewIfNeeded()
  await page.locator('.shot-panel').screenshot({ path: `/tmp/open-corridor-opened-${mobile ? 'mobile' : 'desktop'}.png` })
  await panel.getByRole('button', { name: 'Verify the newly opened route', exact: true }).click()
  const proof = panel.getByRole('img', { name: 'Actual next-pot proof after removing ball 1 by potting it', exact: true })
  await expect(proof).toBeVisible()
  expect(await proof.locator('text').allTextContents()).not.toContain('1')
  expect(await proof.locator('text').allTextContents()).toContain('3')
  await proof.scrollIntoViewIfNeeded()
  await page.locator('.shot-panel').screenshot({ path: `/tmp/open-corridor-proof-${mobile ? 'mobile' : 'desktop'}.png` })
  await panel.getByRole('button', { name: 'Restore only ball 1', exact: true }).click()
  await expect(proof).toHaveCount(0)
  const restored = panel.getByRole('img', { name: 'Counterfactual: restoring only ball 1 blocks the opened route', exact: true })
  expect(await restored.locator('text').allTextContents()).toContain('1')
  await expect(panel).toContainText('keeping the actual cue finish and all other balls fixed')
  await panel.getByRole('button', { name: 'Remove only the retained blocker', exact: true }).click()
  await expect(restored).toHaveCount(0)
  const removed = panel.getByRole('img', { name: 'Counterfactual next-pot proof with only retained ball 1 removed', exact: true })
  expect(await removed.locator('text').allTextContents()).not.toContain('1')
  expect(await removed.locator('text').allTextContents()).not.toContain('3')
  await panel.getByRole('button', { name: 'Try the prediction again', exact: true }).click()
  await expect(panel.getByRole('img')).toHaveCount(0)
  await predictions.getByRole('button', { name: 'Pot ball 1', exact: true }).click()
  await panel.getByRole('button', { name: 'Check prediction', exact: true }).click()
  await expect(panel.getByRole('status')).toContainText('Your prediction removes the blocker')
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.getByRole('button', { name: 'Next level', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Start level 46', exact: true })).toBeVisible()
  await expect(panel).toHaveCount(0)
})
